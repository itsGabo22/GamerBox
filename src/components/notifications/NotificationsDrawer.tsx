'use client';

import React from 'react';
import { BellOff, CheckCheck, Gamepad2, Info, Trophy, TrendingUp, UserPlus } from 'lucide-react';
import { useNotificationStore, type NotificationType } from '@/store/useNotificationStore';
import { useTranslation } from '@/i18n/useTranslation';
import { formatRelative } from '@/i18n/format';
import { Modal } from '@/components/ui/Modal';
import { cn } from '@/lib/cn';

const ICON: Record<NotificationType, React.ReactNode> = {
  SYSTEM: <Info size={16} className="text-text-dim" />,
  GAME: <Gamepad2 size={16} className="text-neon-red-bright" />,
  COMPLETED: <Trophy size={16} className="text-mint-green" />,
  LEVEL: <TrendingUp size={16} className="text-mint-green" />,
  FRIEND: <UserPlus size={16} className="text-neon-red-bright" />,
};

/** Activity generated by this account only (no seeded items). */
export const NotificationsDrawer = () => {
  const { isDrawerOpen, closeDrawer, notifications, markAsRead, markAllAsRead } = useNotificationStore();
  const { t, language } = useTranslation();
  const unread = notifications.filter((n) => !n.read).length;

  return (
    <Modal open={isDrawerOpen} onClose={closeDrawer} title={t('notifications.title')} variant="sheet">
      {notifications.length === 0 ? (
        <div className="flex flex-col items-center py-10 text-center">
          <span className="mb-4 flex h-14 w-14 items-center justify-center rounded-full border border-surface-border bg-white/5 text-text-dim">
            <BellOff size={22} aria-hidden />
          </span>
          <p className="font-heading text-base font-bold uppercase tracking-wide text-white">{t('notifications.emptyTitle')}</p>
          <p className="mt-1 max-w-[240px] text-sm text-text-dim">{t('notifications.emptyBody')}</p>
        </div>
      ) : (
        <div className="flex flex-col gap-2">
          {unread > 0 && (
            <button
              type="button"
              onClick={markAllAsRead}
              className="mb-1 flex h-11 items-center gap-2 self-end rounded-full px-3 font-mono text-[11px] font-bold uppercase tracking-wider text-text-dim transition-colors hover:text-white"
            >
              <CheckCheck size={15} aria-hidden />
              {t('notifications.markAll')}
            </button>
          )}
          <ul className="flex flex-col gap-2">
            {notifications.map((n) => (
              <li key={n.id}>
                <button
                  type="button"
                  onClick={() => markAsRead(n.id)}
                  className={cn(
                    'relative flex w-full gap-3 rounded-2xl border p-4 text-left transition-colors duration-150',
                    n.read ? 'border-transparent opacity-60' : 'border-surface-border bg-white/5'
                  )}
                >
                  <span className="mt-0.5 flex h-9 w-9 shrink-0 items-center justify-center rounded-full border border-surface-border bg-obsidian-black">
                    {ICON[n.type] || ICON.SYSTEM}
                  </span>
                  <span className="min-w-0 flex-1">
                    <span className={cn('block text-sm text-white', !n.read && 'font-bold')}>{t(n.titleKey, n.params)}</span>
                    <span className="mt-0.5 block text-xs leading-relaxed text-text-dim">{t(n.bodyKey, n.params)}</span>
                    <span className="mt-1.5 block font-mono text-[10px] uppercase text-text-dim/70">
                      {formatRelative(n.createdAt, language, t('notifications.now'))}
                    </span>
                  </span>
                  {!n.read && <span className="absolute right-4 top-4 h-2 w-2 rounded-full bg-neon-red-bright" aria-hidden />}
                </button>
              </li>
            ))}
          </ul>
        </div>
      )}
    </Modal>
  );
};
