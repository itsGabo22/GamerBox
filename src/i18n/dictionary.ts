export const dictionary = { es, en };

export type Language = keyof typeof dictionary;
export type TParams = Record<string, string | number>;

export const getTranslation = (lang: Language, path: string, params?: TParams): string => {
  let current: unknown = dictionary[lang] ?? dictionary.es;
  for (const key of path.split('.')) {
    if (typeof current === 'object' && current !== null && key in (current as Record<string, unknown>)) {
      current = (current as Record<string, unknown>)[key];
    } else {
      if (process.env.NODE_ENV !== 'production') console.warn(`[i18n] missing key "${path}" (${lang})`);
      return path;
    }
  }
  if (typeof current !== 'string') return path;
  if (!params) return current;
  return current.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
};
